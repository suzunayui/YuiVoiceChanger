const assert=require('node:assert/strict');
const {adoptManualTiming,latencySignature,calibrationStartConfig}=require('../electron/manual-delay.cjs');
const {normalize}=require('../electron/config.cjs');
const config=normalize({singing_enabled:true,singing_latency_ms:200,obs_correction_ms:300,obs_delay_manual:true});
const timing={previous_base_ms:200,previous_correction_ms:300,singing_latency_ms:330,obs_correction_ms:170};
const adjusted=adoptManualTiming(config,timing);
assert.equal(adjusted.singing_latency_ms,330);assert.equal(adjusted.obs_correction_ms,170);
assert.equal(adjusted.singing_latency_ms+adjusted.obs_correction_ms,500);
for(const patch of [{previous_base_ms:300},{previous_correction_ms:690},{obs_correction_ms:180},{singing_latency_ms:100},{singing_latency_ms:330.5},{obs_correction_ms:NaN}])assert.equal(adoptManualTiming(config,{...timing,...patch}),null);
assert.equal(adoptManualTiming({...config,obs_delay_manual:false},timing),null);
assert.equal(adoptManualTiming({...config,singing_enabled:false},timing),null);
assert.equal(adoptManualTiming(config,null),null);
assert.equal(normalize({}).obs_delay_manual,false);
assert.throws(()=>normalize({obs_delay_manual:1}));
for(const obs_path_delay_ms of [1001,-1001,.5])assert.throws(()=>normalize({obs_path_delay_ms}));
assert.throws(()=>normalize({obs_path_signature:'x'.repeat(8193)}));
assert.equal(latencySignature({beatrice_model:'声.pt.gz',beatrice_voice:2,compute:'cuda:0',input_name:'Mic',output_name:'Cable',obs_port:4455,obs_input_uuid:'music'}),'["声.pt.gz",2,"cuda:0","Mic","Cable",4455,"music"]');
const measured={...config,obs_path_delay_ms:139,obs_path_signature:latencySignature(config)};
assert.equal(normalize(measured).obs_path_signature,measured.obs_path_signature);
assert.equal(normalize(measured,{importing:true}).obs_path_signature,'');
const legacy={...config,obs_delay_manual:false,obs_correction_ms:690};
const migrated=adoptManualTiming(legacy,{legacy_timing:true,previous_base_ms:200,previous_correction_ms:690,singing_latency_ms:380,obs_correction_ms:0});
assert.equal(migrated.singing_latency_ms,380);assert.equal(migrated.obs_correction_ms,0);assert.equal(migrated.obs_delay_manual,true);
assert.equal(adoptManualTiming(legacy,{...timing,legacy_timing:true,previous_correction_ms:690}),null);
assert.equal(adoptManualTiming(config,{...timing,legacy_timing:true}),null);
const prepared=calibrationStartConfig(measured);assert.equal(prepared.singing_latency_ms,361);assert.equal(prepared.obs_correction_ms,139);assert.equal(prepared.obs_delay_manual,false);
const short=calibrationStartConfig({...measured,singing_latency_ms:200,obs_correction_ms:0});assert.equal(short.singing_latency_ms,200);assert.equal(short.obs_delay_manual,false);
assert.equal(calibrationStartConfig(legacy),legacy);
console.log('PASS manual delay reservation adopts only matching startup adjustments and preserves the chosen total');
