const {_electron:electron}=require('@playwright/test');
const {addAndUseModel,openModelLibrary,editModel}=require('./helpers/model-library.cjs');
const fs=require('node:fs'),os=require('node:os'),path=require('node:path'),assert=require('node:assert/strict');
(async()=>{
 const home=fs.mkdtempSync(path.join(os.tmpdir(),'yvc-history-ui-'));
 const first=path.join(home,'first.pt.gz'),second=path.join(home,'second.pt.gz');
 fs.writeFileSync(first,'fixture');fs.writeFileSync(second,'fixture');
 fs.writeFileSync(path.join(home,'desktop.json'),JSON.stringify({engine_version:2,beatrice_model:first,beatrice_voice:1,beatrice_model_label:'以前の自動名'}));
 const options={...(process.env.YVC_TEST_EXECUTABLE?{executablePath:process.env.YVC_TEST_EXECUTABLE,args:[]}:{args:[path.resolve('.')]}),env:{...process.env,YVC_DESKTOP_HOME:home}};
 let app;
 try{
  app=await electron.launch(options);let page=await app.firstWindow();
  await page.getByRole('button',{name:'◉ 声を変える',exact:true}).click();
  await page.getByRole('heading',{name:'first.pt.gz',exact:true}).waitFor();
  await editModel(page,'first.pt.gz');
  await page.getByRole('textbox',{name:'モデルの別名',exact:true}).fill('声A');
  await page.getByRole('button',{name:'保存',exact:true}).click();
  await page.getByRole('button',{name:'モデル一覧を閉じる',exact:true}).click();
  await page.getByRole('heading',{name:'声A',exact:true}).waitFor();
  assert.equal(fs.readFileSync(first,'utf8'),'fixture');
  assert(await page.evaluate(file=>window.yvc.invoke('rename-model',{path:file,voice:0,alias:'wrong'}).then(()=>false,()=>true),second));
  assert(await page.evaluate(file=>window.yvc.invoke('rename-model',{path:file,voice:1,alias:'x'.repeat(81)}).then(()=>false,()=>true),first));
  await app.evaluate(({dialog},file)=>{dialog.showOpenDialog=async()=>({canceled:false,filePaths:[file]});},second);
  await addAndUseModel(page,'second.pt.gz');
  await page.getByRole('heading',{name:'second.pt.gz',exact:true}).waitFor();
  const recent=await page.evaluate(()=>window.yvc.invoke('model-history'));
  assert.equal(recent.length,2);
  const library=await openModelLibrary(page);
  await library.getByRole('button',{name:'モデルを選択：声A',exact:true}).click();
  assert.equal((await page.evaluate(()=>window.yvc.invoke('config'))).beatrice_model,second);
  await library.getByRole('button',{name:'モデルを選択：second.pt.gz',exact:true}).click();
  assert(await library.getByRole('button',{name:'このモデルに切り替える',exact:true}).isDisabled());
  await library.getByRole('button',{name:'モデルを選択：声A',exact:true}).click();
  await library.getByRole('button',{name:'このモデルに切り替える',exact:true}).click();
  await page.waitForFunction(async()=>{const c=await window.yvc.invoke('config');return c.beatrice_voice===1&&c.beatrice_model_alias==='声A';});
  await app.close();app=await electron.launch(options);page=await app.firstWindow();
  await page.getByRole('button',{name:'◉ 声を変える',exact:true}).click();
  const saved=await page.evaluate(()=>window.yvc.invoke('model-history'));
  assert.equal(saved.length,2);assert.equal(saved[0].label,'声A');
  await editModel(page,'声A');
  await page.getByRole('textbox',{name:'モデルの別名',exact:true}).fill('キャンセルした名前');
  await page.getByRole('button',{name:'キャンセル',exact:true}).click();
  await page.getByRole('button',{name:'モデル一覧を閉じる',exact:true}).click();
  await page.getByRole('heading',{name:'声A',exact:true}).waitFor();
  await editModel(page,'声A');
  await page.getByRole('button',{name:'ファイル名に戻す',exact:true}).click();
  await page.getByRole('button',{name:'保存',exact:true}).click();
  await page.getByRole('button',{name:'モデル一覧を閉じる',exact:true}).click();
  await page.getByRole('heading',{name:'first.pt.gz',exact:true}).waitFor();
  assert.equal((await page.evaluate(()=>window.yvc.invoke('model-history')))[0].alias,'');
  fs.unlinkSync(second);
  assert(await page.evaluate(id=>window.yvc.invoke('select-model-history',id).then(()=>false,()=>true),saved.find(item=>item.voice===0).id));
  assert.equal((await page.evaluate(()=>window.yvc.invoke('config'))).beatrice_model,first);
  console.log('PASS filename default, explicit alias, immutable model file, alias validation, history/restart persistence, cancellation and reset');
 }finally{if(app)await app.close();fs.rmSync(home,{recursive:true,force:true});}
})().catch(error=>{console.error(error);process.exitCode=1;});
